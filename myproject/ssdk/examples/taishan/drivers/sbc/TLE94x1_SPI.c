uint8_t SBC_SPI_INIT(void)
{

    if (sdrv_spi_controller_probe(&sbc_spi_controller, &sbc_spi_config,
                                  &sbc_spi_controller_conf)) {
        printf("controller_init error\n");
    }

    if (spi_init(&sbc_spi_device, &sbc_spi_controller, &sbc_spi_device_conf)) {
        printf("device init error\n");
    }

    gpio_dev = GPIO_INSTANCE(SBC_SPI_CS);
    pinctrl = PINCTRL_INSTANCE(SBC_SPI_CS);

    SBC_SPI_SET;
    return 0;
}

uint16_t SBC_SPI_TRANSFER16(uint8_t Upper, uint8_t Lower)
{
    uint8_t txBuf[2] = {0};
    uint8_t rxBuf[2] = {0};
    uint16_t outdata = 0;

    txBuf[0] = Upper;
    txBuf[1] = Lower;

    SBC_SPI_RESET;
    spi_transfer(&sbc_spi_controller, &sbc_spi_device, txBuf, rxBuf, 2, 100000);
    SBC_SPI_SET;

    /* CSN High Time at least 3us. See datasheet 162 */
    udelay(3);

    outdata = rxBuf[0];
    outdata <<= 8;
    outdata |= rxBuf[1];

    return outdata;
}
