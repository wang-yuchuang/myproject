static bool sdrv_msa03_board_deinit(am_board_t *board)
{
    /* path codec unregister , codec destroy ,drvdata realse */
    am_codec_t *ak7738_codec = am_board_find_codec(board, MSA03_CODEC_AK7738);
    ak7738_drvdata_t *drvdata =
        (ak7738_drvdata_t *)am_codec_get_drvdata(ak7738_codec);

    am_board_remove_path(board, &idle_path);
    am_board_remove_path(board, &hifi_playback_path);
    am_board_remove_path(board, &hifi_capture_path);
    am_board_remove_path(board, &cluster_playback_path);
    am_board_remove_path(board, &safety_playback_path);
    am_board_remove_path(board, &fm_playback_path);
    am_board_remove_path(board, &tbox_playback_path);
    am_board_remove_path(board, &phone_playback_path);
    am_board_remove_path(board, &phone_capture_path);
    am_board_remove_path(board, &nav_playback_path);
    am_board_remove_codec(board, ak7738_codec);

    ak7738_codec_destroy(ak7738_codec);

    return true;
}

static bool sdrv_msa03_board_reset(am_board_t *board)
{

    am_codec_t *ak7738_codec = am_board_find_codec(board, MSA03_CODEC_AK7738);
    bool ret;

    /* Ak7738 reset by GPIO */
    ret = am_write_ctl_nocache(ak7738_codec, AK7738_106_01_VIR_HWPDN, 0x0);
    am_delay(5);
    ret = am_write_ctl_nocache(ak7738_codec, AK7738_106_01_VIR_HWPDN, 0x1);
    am_delay(5);

    /* load firmware */
    ret = am_burn_fw(ak7738_codec, AK7738_FW_NO5_DSP1);
    ret = am_burn_fw(ak7738_codec, AK7738_FW_NO5_DSP2);
    return ret;
}

