#!/bin/bash
# build.sh — legacy_app 构建入口
#
# 一键完成：源码编译 → ext4 → dm-verity hashtree → D9APPMD1 签名 → RAUC bundle
# 输出: remote_pkg/app-<version>.raucb
#
# 用法:
#   ./build.sh                # 完整构建（编译 + 签名 + RAUC bundle）
#   ./build.sh build          # 仅编译
#   ./build.sh clean          # 清理

set -euo pipefail

# ── 项目路径 ──────────────────────────────────────────────────
PROJECT_ROOT="$(cd "$(dirname "$0")" && pwd)"
SOURCE_DIR="${PROJECT_ROOT}/src"
OUTPUT_DIR="${PROJECT_ROOT}/out"
PKG_DIR="${PROJECT_ROOT}/pkg"
REMOTE_PKG_DIR="${PROJECT_ROOT}/remote_pkg"
SCRIPTS_DIR="${PROJECT_ROOT}/scripts"

# ── 生产配置（写死，避免误配） ─────────────────────────────────
SIGN_URL="http://192.168.34.207:8900"
SIGN_TOKEN="token-d9-sdk-001"
KEY_ID="ota_signing"
PARTITION_SIZE="256M"
RAUC_COMPATIBLE="${RAUC_COMPATIBLE:-bmu05_a00}"
MU_TYPE="mu2"
METADATA_VERSION="1"

# ── 版本号自动生成 ─────────────────────────────────────────────
auto_version() {
    local ds="$(date +%Y%m%d)"
    if [ -d "${PROJECT_ROOT}/.git" ]; then
        local gd
        gd="$(cd "${PROJECT_ROOT}" && git describe --tags --always 2>/dev/null)" || true
        if [ -n "$gd" ]; then
            if echo "$gd" | grep -qE '^[0-9a-f]+$'; then
                echo "dev-${gd:0:8}-${ds}"
            else
                echo "${gd}-${ds}"
            fi
            return
        fi
    fi
    echo "dev-${ds}"
}
APP_VERSION="$(auto_version)"
APP_IMG="app-${APP_VERSION}.img"
APP_RAUCB="app-${APP_VERSION}.raucb"

# ── 参数解析 ──────────────────────────────────────────────────
ACTION="${1:-all}"
case "${ACTION}" in
    build)  ;;
    clean)  ;;
    all)    ;;
    --help) echo "用法: ./build.sh [build|clean]"; exit 0 ;;
    *) echo "错误: 未知参数 '${ACTION}'"; exit 1 ;;
esac

# ── 前置检查 ──────────────────────────────────────────────────
command -v aarch64-linux-gnu-gcc >/dev/null 2>&1 || {
    echo "错误: 未找到 aarch64-linux-gnu-gcc 交叉编译器"
    exit 1
}

# ── 环境变量（原 mkenv_arm_st 内联） ──────────────────────────
export NCCU_CROSS_PLATFORM="arm"
export GCC_PREFIX=""
export NCCU_SOURCE_DIR="${SOURCE_DIR}"
export NCCU_TARGET_DIR="${OUTPUT_DIR}"
export NCCU_PKG_DIR="${PKG_DIR}"
export NCCU_IMG_DIR="${REMOTE_PKG_DIR}"
export NCCU_MAKE_MANIF="ST"
export NCCU_SKIP_ENCRYPT="1"

mkdir -p "${OUTPUT_DIR}" "${PKG_DIR}" "${REMOTE_PKG_DIR}"

# ═══════════════════════════════════════════════════════════════
# 函数
# ═══════════════════════════════════════════════════════════════

do_compile() {
    echo "[build.sh] 编译 (${MU_TYPE})..."
    # 注入版本号到源码
    cat > "${SOURCE_DIR}/version_patch.h" << VERSIONEOF
// Auto-generated by build.sh
#define SWVERSION_PATCH_NUMBER  "${APP_VERSION}"
VERSIONEOF
    (
        cd "${SOURCE_DIR}"
        bash mk_define release "${MU_TYPE}"
        MU_TYPE="${MU_TYPE}" make install
    )
    echo "[build.sh] 编译完成"
}

do_package() {
    echo "[build.sh] 打包..."
    local part_bytes=$(( ${PARTITION_SIZE%M} * 1024 * 1024 ))
    local overhead=$(( part_bytes / 100 * 2 + 4096 ))
    local ext4_bytes=$(( part_bytes - overhead ))

    "${SCRIPTS_DIR}/create_ext4.sh" --input-dir "${OUTPUT_DIR}" \
        --output "${PKG_DIR}/app.ext4" --size "${ext4_bytes}"
    "${SCRIPTS_DIR}/generate_verity.sh" --image "${PKG_DIR}/app.ext4" \
        --output-dir "${PKG_DIR}" --block-size 4096

    local bs
    bs=$(dumpe2fs -h "${PKG_DIR}/app.ext4" 2>/dev/null | grep 'Block size' | awk '{print $NF}')
    [ "${bs}" = "4096" ] || { echo "错误: ext4 block size=${bs}"; exit 1; }

    # shellcheck disable=SC2086
    "${SCRIPTS_DIR}/sign_metadata.sh" \
        --image "${PKG_DIR}/app.ext4" \
        --hashtree "${PKG_DIR}/app_hashtree.bin" \
        --version "${APP_VERSION}" \
        --metadata-version "${METADATA_VERSION}" \
        --key-id "${KEY_ID}" \
        --output-dir "${PKG_DIR}" \
        --sign-url "${SIGN_URL}/api/v1/sign" \
        --sign-token "${SIGN_TOKEN}"

    local sig_file=""
    [ -f "${PKG_DIR}/metadata.sig" ] && sig_file="--signature ${PKG_DIR}/metadata.sig"
    # shellcheck disable=SC2086
    "${SCRIPTS_DIR}/assemble_image.sh" \
        --ext4 "${PKG_DIR}/app.ext4" \
        --hashtree "${PKG_DIR}/app_hashtree.bin" \
        --metadata "${PKG_DIR}/metadata.bin" ${sig_file} \
        --output "${PKG_DIR}/${APP_IMG}" \
        --partition-size "${PARTITION_SIZE}"

    local magic
    magic=$(dd if="${PKG_DIR}/${APP_IMG}" bs=1 skip=$((part_bytes - 4096)) count=8 2>/dev/null)
    [ "${magic}" = "D9APPMD1" ] || { echo "错误: metadata magic=${magic}"; exit 1; }
    echo "[build.sh] app.img: ${PKG_DIR}/${APP_IMG}"
}

do_rauc_bundle() {
    echo "[build.sh] RAUC bundle..."
    local bundle_out="${REMOTE_PKG_DIR}/${APP_RAUCB}"

    bash "${SCRIPTS_DIR}/ota-bundle.sh" \
        --app-image "${PKG_DIR}/${APP_IMG}" \
        --output "${bundle_out}" \
        --version "${APP_VERSION}" \
        --compatible "${RAUC_COMPATIBLE}" \
        --sign-url "${SIGN_URL}" \
        --sign-token "${SIGN_TOKEN}" \
        --sign-key-id "${KEY_ID}" 2>&1 | grep -v '^rauc-Message:\|^C0'

    # 清理中间产物
    rm -f "${PKG_DIR}/app.ext4" "${PKG_DIR}/app_hashtree.bin" \
          "${PKG_DIR}/metadata.bin" "${PKG_DIR}/metadata.sig" \
          "${PKG_DIR}/verity_info.txt" "${PKG_DIR}/_gen_verity.py"
    rm -f "${PKG_DIR}/app_nccu.tar.gz" "${PKG_DIR}/pkg.sum"
    rm -rf "${PKG_DIR}/tmp"

    echo "[build.sh] ✅ ${bundle_out}"
}

# ── 分发 ──────────────────────────────────────────────────────
case "${ACTION}" in
    clean)
        echo "[build.sh] 清理..."
        (cd "${SOURCE_DIR}" && make clean >/dev/null 2>&1 || true)
        rm -rf "${OUTPUT_DIR}"/* "${PKG_DIR}"/* "${REMOTE_PKG_DIR}"/*
        echo "[build.sh] 清理完成"
        ;;
    build)
        do_compile
        ;;
    all)
        do_compile
        do_package
        do_rauc_bundle
        ;;
esac
