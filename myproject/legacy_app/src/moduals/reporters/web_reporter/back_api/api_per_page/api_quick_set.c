static BOOL Parse_and_Handle_QuickSet(FCGI_ROUGH_DATA* pFCGI_Rough)
{
    if(!s_bIsCreateQuickMenu_OK)
    {
        // Make_Web_OutPut(104, "The 'quick_set munu' is NOT created yet!", NULL, NULL);
        // return FALSE;
        Create_QuickSetMenus(pFCGI_Rough);
        s_bIsCreateQuickMenu_OK = TRUE;
    }

    int n;
    cJSON* pJsonSet = cJSON_Parse(pFCGI_Rough->szBodyRaw);
    if(pJsonSet == NULL)
    {
        TRACEX("--The ParamSet string is not a JSON->[%s]----\n", pFCGI_Rough->szBodyRaw);
        Make_Web_OutPut(104, "The 'param to be set' is NOT valid Json string!", NULL, NULL);
        return FALSE;
    }
    cJSON* temp;
    //parse menu_id
    if((temp = cJSON_GetObjectItem(pJsonSet, "qmenu")) == NULL)
    {
        Make_Web_OutPut(104, "The 'qmenu' is NOT provided!", NULL, NULL);
        cJSON_Delete(pJsonSet);
        return FALSE;
    }
    int nMenuId = temp->valueint;
    if((nMenuId < 0) || (nMenuId >= QUICKSET_MENUID_MAX))
    {
        Make_Web_OutPut(104, "The 'qmenu' is OUT of range!", NULL, NULL);
        cJSON_Delete(pJsonSet);
        return FALSE;
    }
    //parse val_list
    char *szValString = NULL;
    cJSON* pJValList = cJSON_GetObjectItem(pJsonSet, "val_list");   
    if(pJValList != NULL)
    {
        if(pJValList->type != cJSON_Array)
        {
            Make_Web_OutPut(104, "The 'val_list' NOT array!", NULL, NULL);
            cJSON_Delete(pJsonSet);
            return FALSE;
        }
    }
    else 
    {
        Make_Web_OutPut(104, "The 'val_list' can NOT be empty!", NULL, NULL);
        cJSON_Delete(pJsonSet);
        return FALSE;
    }

    int nParam2SetTotal = cJSON_GetArraySize(pJValList);
    cJSON* temp1;
    int nParamId;
    //every manu can have only one blob
    A_WEBBLOB_PARAM blobParamVal; 
    BOOL bIsBlobCreated = FALSE;
    int nDevId_4Blob = -1;
    int nSetCtrl_ExeRtn = WEB_ERRCODE_OK;
    for(n = 0; n < nParam2SetTotal; n++)
    {
        cJSON* pJParamVal = cJSON_GetArrayItem(pJValList, n);
        if(pJParamVal == NULL)
        {
            Make_Web_OutPut(104, "Parse param array error!", NULL, NULL);
            cJSON_Delete(pJsonSet);
            return FALSE;
        }
        else if(pJParamVal->type != cJSON_Object)
        {
            Make_Web_OutPut(104, "The val_list format is WRONG!", NULL, NULL);
            cJSON_Delete(pJsonSet);
            return FALSE;
        }
        if((temp1 = cJSON_GetObjectItem(pJParamVal, "param_id")) == NULL)
        {
            Make_Web_OutPut(104, "The 'param_id' NOT found!", NULL, NULL);
            cJSON_Delete(pJsonSet);
            return FALSE;
        }
        nParamId = temp1->valueint;        
        if((temp1 = cJSON_GetObjectItem(pJParamVal, "val_string")) == NULL)
        {
            Make_Web_OutPut(104, "The 'val_string' NOT found!", NULL, NULL);
            cJSON_Delete(pJsonSet);
            return FALSE;
        }
        else if((temp1->valuestring == NULL) || (temp1->type != cJSON_String))
        {
            Make_Web_OutPut(104, "The 'val_string' string NOT correct!", NULL, NULL);
            cJSON_Delete(pJsonSet);
            return FALSE;
        }

        //now judge the param
        QUICK_PARAM_VALUE* pQuickIt = Get_QuickParaItem_byId(nMenuId, nParamId);
        if(pQuickIt == NULL)
        {
            Make_Web_OutPut(104, "No such quick param found!", NULL, NULL);
            cJSON_Delete(pJsonSet);
            return FALSE;
        }
        else if(pQuickIt->bIsBlobparam)
        {
            if(!bIsBlobCreated)
            {
                if(!Create_AWebBlob_Param(&blobParamVal, pQuickIt->pOrigParam, NULL))
                {
                    Make_Web_OutPut(104, "Can NOT create the blob!", NULL, NULL);
                    cJSON_Delete(pJsonSet);
                    return FALSE;
                }
                else
                {
                    bIsBlobCreated = TRUE;
                    nDevId_4Blob = pQuickIt->nDevId;
                }                
            }
            //now set the string to the sub-blob
            if(!SetStr_2WebSubBlob_ParamVal(&blobParamVal, (nParamId % 1000), 
                temp1->valuestring, strlen(temp1->valuestring)))
            {
                Make_Web_OutPut(104, "Can NOT set the value for a SubBlobParam!", NULL, NULL);
                cJSON_Delete(pJsonSet);                
                return FALSE;
            }   
        }
        else
        {
            if(Handle_SingleParam_SetCtrl(pQuickIt->pOrigParam, pQuickIt->nDevId, 
                temp1->valuestring, strlen(temp1->valuestring)) != WEB_ERRCODE_OK)
            {
                Make_Web_OutPut(104, "Can NOT set the value for a param!", NULL, NULL);
                cJSON_Delete(pJsonSet);                
                return FALSE;               
            }
        }   

    }//for

    //now do not forget to set the blob param seperatedly
    if(bIsBlobCreated)
    {
        nSetCtrl_ExeRtn = Handle_SingleParam_SetCtrl(blobParamVal.pParamVal, nDevId_4Blob, blobParamVal.pBlobVal_Raw, 
                blobParamVal.pParamVal->nBlobSize);
        Delete_AWebBlob_Param(&blobParamVal);    
    }  
        
    if(nSetCtrl_ExeRtn == WEB_ERRCODE_OK)
    {
        //now send back the refreshed run 
        Force_Update_ParamVals();
        Prepare_QuickSet_Get(pFCGI_Rough, nMenuId);
    }
    else
    {
        char szErrCode[64];
        snprintf(szErrCode, 64, "Execute errorCode=>%d!", nSetCtrl_ExeRtn);
        Make_Web_OutPut(104, szErrCode, "Param Set Error!", NULL);
        cJSON_Delete(pJsonSet);
        //also need update it
        Force_Update_ParamVals();
        return FALSE;
    }

    WEB_PARAM_VALUE* pParamVal = Get_ASingle_WebParaVal(PARAM_TYPE_SETTING, 1, 89);
    char* szVal = "2";
    nSetCtrl_ExeRtn =  Handle_SingleParam_SetCtrl(pParamVal, 1, szVal, strlen(szVal));
    if(nSetCtrl_ExeRtn != WEB_ERRCODE_OK)
    {
        Make_Web_OutPut(104, "Can NOT set control the value for a param!", NULL, NULL);
        return FALSE; 
    }
    
    cJSON_Delete(pJsonSet);
    return TRUE;   
}


BOOL webpage_handler_quick_set(FCGI_ROUGH_DATA* pFCGI_Rough)
{
    int n;
    TRACEX("\n----QUICK_SET page_handler was called!---\n");

    if(pFCGI_Rough->emHttpReqMethod == HTTP_REQMETHOD_GET)
    {
        int nMenuIdx = -1;
        //if(!ParseInt_FromQuery(pFCGI_Rough->szQueryRaw, "qmenu=", &nMenuIdx))
        if(!ParseInt_FromQuery(pFCGI_Rough->szQueryRaw, "type=", &nMenuIdx))
        {
            Make_Web_OutPut(104, "The 'qmenu' NOT provided!", NULL, NULL);
            return FALSE;  
        }

        if((nMenuIdx >= 0) && (nMenuIdx < QUICKSET_MENUID_MAX))
        {
            return Prepare_QuickSet_Get(pFCGI_Rough, nMenuIdx);
        }
        else
        {
            Make_Web_OutPut(104, "The 'qmenu' value INVALID!", NULL, NULL);
            return FALSE;  
        }
    }
    else
    {
        //now need parse amd handle quieck_set data
        return Parse_and_Handle_QuickSet(pFCGI_Rough);
    }
    
    return FALSE;
}