static bool refa04_set_path_vol(am_path_t *path, unsigned int vol)
{
    am_codec_t *tas6424_codec =
        am_board_find_codec(path->board, REFA04_CODEC_TAS6424);
    int vol_index =
        am_get_linear_vol(vol, TAS6424_CH_VOLUME_MAX, TAS6424_CH_VOLUME_MIN);
    bool ret;

    if (!tas6424_codec) {
        ssdk_printf(SSDK_ERR, "Func %s tas6424_codec is null  \n", __FUNCTION__);
        ERRCODE_PRINT(MOD_ID_SYS_SERVICE_AUDIO, AUDIO_MANAGER_SVC,
                      RET_ERR_SETVOL_FAILED, vol);
        return false;
    }

    ret = am_write_ctl(tas6424_codec, TAS6424_05_FF_CH1_VOLUME, vol_index);
    _CHECK_RET(ret);
    ret = am_write_ctl(tas6424_codec, TAS6424_06_FF_CH2_VOLUME, vol_index);
    _CHECK_RET(ret);
    ret = am_write_ctl(tas6424_codec, TAS6424_07_FF_CH3_VOLUME, vol_index);
    _CHECK_RET(ret);
    ret = am_write_ctl(tas6424_codec, TAS6424_08_FF_CH4_VOLUME, vol_index);
    _CHECK_RET(ret);

    return true;
}

