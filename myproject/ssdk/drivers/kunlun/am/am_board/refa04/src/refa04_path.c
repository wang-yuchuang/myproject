bool refa04_ak7738_ctl_pdn_put(am_codec_t *dev, unsigned int ctl,
                               unsigned int enable)
{
    gpio_dev_t *handle = get_tca9539_handle();

    if (!handle) {
        ssdk_printf(SSDK_ERR, "Func %s tca9539 handle is null \n", __FUNCTION__);
        ERRCODE_PRINT(MOD_ID_SYS_SERVICE_AUDIO, AUDIO_MANAGER_SVC,
                      RET_ERR_INIT_FAILED, ctl);
        return false;
    }

    if (enable) {
        handle->ops->config(handle, AUDIO_DSP_RST_N,GPIO_OUT);
        handle->ops->set(handle, AUDIO_DSP_RST_N, 1);
    }
    else {
        handle->ops->config(handle, AUDIO_DSP_RST_N,GPIO_OUT);
        handle->ops->set(handle, AUDIO_DSP_RST_N, 0);
    }

    ssdk_printf(REFA04_PATH_DBG_PRT, "%s refa04 ctl_id =%d,enable=%d\n", __func__,
            ctl, enable);

    return true;
}

static bool is_codec(am_codec_t *codec, const char *name)
{

    if (!strcmp(codec->name, name)) {
        return true;
    }

    return false;
}

bool refa04_ctl_put(am_codec_t *codec, unsigned int ctl, unsigned int enable)
{
    gpio_dev_t *handle = get_tca9539_handle();
    unsigned int pin_index = 0;

    if (!handle) {
        ssdk_printf(SSDK_ERR, "Func %s tca9539 handle is null \n", __FUNCTION__);
        ERRCODE_PRINT(MOD_ID_SYS_SERVICE_AUDIO, AUDIO_MANAGER_SVC,
                      RET_ERR_INIT_FAILED, ctl);
        return false;
    }

    if (is_codec(codec, REFA04_CODEC_AK7738)) {

        switch (ctl) {
            case AK7738_106_01_VIR_HWPDN:
                pin_index = AUDIO_DSP_RST_N;
                break;

            default: {
                ERRCODE_PRINT(MOD_ID_SYS_SERVICE_AUDIO, AUDIO_MANAGER_SVC,
                              RET_ERR_PARAM_FAILED, ctl);
                ssdk_printf(SSDK_ERR, "put: codec(%s) unsuppoort  ctl(%d)\n",
                        codec->name, ctl);
                return false;
            }
        }
    }
    else if (is_codec(codec, REFA04_CODEC_TAS6424)) {

        switch (ctl) {
            case TAS6424_29_01_VIR_STANDBY_N:
                pin_index = AUDIO_DIG_AMP_STANDBY_N;
                break;

            case TAS6424_30_01_VIR_MUTE_N:
                pin_index = AUDIO_DIG_AMP_MUTE_N;
                break;

            default: {
                ERRCODE_PRINT(MOD_ID_SYS_SERVICE_AUDIO, AUDIO_MANAGER_SVC,
                              RET_ERR_PARAM_FAILED, ctl);
                ssdk_printf(SSDK_ERR, "put: codec(%s) unsuppoort  ctl(%d)\n",
                        codec->name, ctl);
                return false;
            }
        }
    }
    else if (is_codec(codec, REFA04_CODEC_TAS5404)) {

        switch (ctl) {
            case TAS5404_14_01_VIR_FAULT_N:
                pin_index = AUDIO_ANA_AMP_FAULT_N;
                break;

            case TAS5404_15_01_VIR_CLIP_OTW_N:
                pin_index = AUDIO_ANA_AMP_CLIP_OTW_N;
                break;

            default: {
                ERRCODE_PRINT(MOD_ID_SYS_SERVICE_AUDIO, AUDIO_MANAGER_SVC,
                              RET_ERR_PARAM_FAILED, ctl);
                ssdk_printf(SSDK_ERR, "put: codec(%s) unsuppoort  ctl(%d)\n",
                        codec->name, ctl);
                return false;
            }
        }
    }
    else if (is_codec(codec, REFA04_CODEC_XF6020)) {

        switch (ctl) {
            case XF6020_0D_01_RESET:
                pin_index = AUDIO_4MIC_RST_N;
                break;

            default: {
                ERRCODE_PRINT(MOD_ID_SYS_SERVICE_AUDIO, AUDIO_MANAGER_SVC,
                              RET_ERR_PARAM_FAILED, ctl);
                ssdk_printf(SSDK_ERR, "put: codec(%s) unsuppoort  ctl(%d)\n",
                        codec->name, ctl);
                return false;
            }
        }
    }
    else {
        ssdk_printf(SSDK_ERR, "Func %s unsuppoort codec\n", __FUNCTION__);
        return false;
    }

    if (enable) {
        handle->ops->config(handle, pin_index,GPIO_OUT);
        handle->ops->set(handle, pin_index, 1);
    }
    else {
        handle->ops->config(handle, pin_index,GPIO_OUT);
        handle->ops->set(handle, pin_index, 0);
    }

    ssdk_printf(REFA04_PATH_DBG_PRT, "%s refa04 ctl_id =%d,enable=%d\n", __func__,
            ctl, enable);

    return true;
}

bool refa04_ctl_get(am_codec_t *codec, unsigned int ctl, unsigned int *val)
{
    gpio_dev_t *handle = get_tca9539_handle();
    unsigned int pin_index = 0;

    if (!handle) {
        ssdk_printf(SSDK_ERR, "Func %s tca9539 handle is null \n", __FUNCTION__);
        return false;
    }

    if (is_codec(codec, REFA04_CODEC_TAS6424)) {

        switch (ctl) {
            case TAS6424_31_01_VIR_FAULT_N:
                pin_index = AUDIO_DIG_AMP_FAULT_N;
                break;

            case TAS6424_32_01_VIR_WARN_N:
                pin_index = AUDIO_DIG_AMP_WARN_N;
                break;

            default: {
                ERRCODE_PRINT(MOD_ID_SYS_SERVICE_AUDIO, AUDIO_MANAGER_SVC,
                              RET_ERR_PARAM_FAILED, ctl);
                ssdk_printf(SSDK_ERR, "get: codec(%s) unsuppoort  ctl(%d)\n",
                        codec->name, ctl);
                return false;
            }
        }
    }
    else if (is_codec(codec, REFA04_CODEC_TAS5404)) {
        switch (ctl) {
            case TAS5404_14_01_VIR_FAULT_N:
                pin_index = AUDIO_ANA_AMP_FAULT_N;
                break;

            case TAS5404_15_01_VIR_CLIP_OTW_N:
                pin_index = AUDIO_ANA_AMP_CLIP_OTW_N;
                break;

            default: {
                ERRCODE_PRINT(MOD_ID_SYS_SERVICE_AUDIO, AUDIO_MANAGER_SVC,
                              RET_ERR_PARAM_FAILED, ctl);
                ssdk_printf(SSDK_ERR, "get: codec(%s) unsuppoort  ctl(%d)\n",
                        codec->name, ctl);
                return false;
            }
        }
    }
    else {
        ERRCODE_PRINT(MOD_ID_SYS_SERVICE_AUDIO, AUDIO_MANAGER_SVC,
                      RET_ERR_PARAM_FAILED, ctl);
        ssdk_printf(SSDK_ERR, "Func %s unsuppoort codec\n", __FUNCTION__);
        return false;
    }

    handle->ops->config(handle, pin_index,GPIO_IN);
    val[0] = handle->ops->get(handle, pin_index);

    ssdk_printf(REFA04_PATH_DBG_PRT, "%s refa04 ctl_id =%d,val=%d\n", __func__, ctl,
            val[0]);
    return true;
}

