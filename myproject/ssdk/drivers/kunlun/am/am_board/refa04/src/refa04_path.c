bool am_refa04_board_init(am_board_t *board)
{
    am_codec_t *ak7738_codec;
    am_codec_t *tas6424_codec;
    am_codec_t *xf6020_codec;
    am_codec_t *tas5404_codec;

    /* register all path for board */
    am_board_add_path(board, &refa04_idle_path);
    am_board_add_path(board, &refa04_hifi_playback_path);
    am_board_add_path(board, &refa04_navi_playback_path);
    am_board_add_path(board, &refa04_hifi_capture_path);
    am_board_add_path(board, &refa04_safety_playback_path);
    am_board_add_path(board, &refa04_bt_playback_16k_path);
    am_board_add_path(board, &refa04_bt_capture_16k_path);
    am_board_add_path(board, &refa04_bt_playback_8k_path);
    am_board_add_path(board, &refa04_bt_acpture_8k_path);

    /* register all codec for board */

    /* AK7738 */
    ak7738_codec = ak7738_codec_create(REFA04_CODEC_AK7738);
    am_board_add_codec(board, ak7738_codec);

    ak7738_drvdata.handle = i2c_get_adap_dev(AUDIO_I2C_INSTANCE);

    if (!ak7738_drvdata.handle) {
        ERRCODE_PRINT(MOD_ID_SYS_SERVICE_AUDIO, AUDIO_MANAGER_SVC,
                  RET_ERR_INIT_FAILED, AUDIO_I2C_INSTANCE);
        ssdk_printf(SSDK_ERR, "Func %s ak7738 i2c handle create faild  \n",
                __FUNCTION__);
        return false;
    }

    am_codec_set_virctl_handler(ak7738_codec, AK7738_106_01_VIR_HWPDN,
                                refa04_ctl_put, NULL);
    am_codec_set_drvdata(ak7738_codec, &ak7738_drvdata);

    tca9539_gpio_init(&g_gpio_tca9539, i2c_get_adap_dev(12), 0, NULL);

    set_tca9539_handle(&g_gpio_tca9539);

    /* TAS6424 */
    tas6424_codec = tas6424_codec_create(REFA04_CODEC_TAS6424);
    am_board_add_codec(board, tas6424_codec);

    tas6424_drvdata.handle = i2c_get_adap_dev(AUDIO_I2C_INSTANCE);

    if (!tas6424_drvdata.handle) {
        ERRCODE_PRINT(MOD_ID_SYS_SERVICE_AUDIO, AUDIO_MANAGER_SVC,
              RET_ERR_INIT_FAILED, AUDIO_I2C_INSTANCE);
        ssdk_printf(SSDK_ERR, "Func %s tas6424 i2c handle create faild  \n",
                __FUNCTION__);
        return false;
    }

    ssdk_printf(SSDK_ERR, "Func %s tas6424 i2c handle:0x%x  \n",
                __FUNCTION__,tas6424_drvdata.handle);

    am_codec_set_virctl_handler(tas6424_codec, TAS6424_29_01_VIR_STANDBY_N,
                                refa04_ctl_put, NULL);
    am_codec_set_virctl_handler(tas6424_codec, TAS6424_30_01_VIR_MUTE_N,
                                refa04_ctl_put, NULL);
    am_codec_set_virctl_handler(tas6424_codec, TAS6424_31_01_VIR_FAULT_N, NULL,
                                refa04_ctl_get);
    am_codec_set_virctl_handler(tas6424_codec, TAS6424_32_01_VIR_WARN_N, NULL,
                                refa04_ctl_get);
    am_codec_set_drvdata(tas6424_codec, &tas6424_drvdata);

    /* XF6020 */
    xf6020_codec = xf6020_codec_create(REFA04_CODEC_XF6020);
    am_board_add_codec(board, xf6020_codec);

    xf6020_drvdata.handle = i2c_get_adap_dev(AUDIO_I2C_INSTANCE);

    if (!xf6020_drvdata.handle) {
        ERRCODE_PRINT(MOD_ID_SYS_SERVICE_AUDIO, AUDIO_MANAGER_SVC,
                  RET_ERR_INIT_FAILED, AUDIO_I2C_INSTANCE);
        ssdk_printf(SSDK_ERR, "Func %s xf6020 i2c handle create faild \n",
                __FUNCTION__);
        return false;
    }

    am_codec_set_drvdata(xf6020_codec, &xf6020_drvdata);
    am_codec_set_virctl_handler(xf6020_codec, XF6020_0D_01_RESET,
                                refa04_ctl_put, NULL);

    /* TAS5404 */
    tas5404_codec = tas5404_codec_create(REFA04_CODEC_TAS5404);
    am_board_add_codec(board, tas5404_codec);

    tas5404_drvdata.handle = i2c_get_adap_dev(AUDIO_I2C_INSTANCE);

    if (!tas5404_drvdata.handle) {
        ERRCODE_PRINT(MOD_ID_SYS_SERVICE_AUDIO, AUDIO_MANAGER_SVC,
                  RET_ERR_INIT_FAILED, AUDIO_I2C_INSTANCE);
        ssdk_printf(SSDK_ERR, "Func %s tas5404 i2c handle create faild  \n",
                __FUNCTION__);
        return false;
    }

    am_codec_set_drvdata(tas5404_codec, &tas5404_drvdata);
    am_codec_set_virctl_handler(tas5404_codec, TAS5404_14_01_VIR_FAULT_N, NULL,
                                refa04_ctl_get);
    am_codec_set_virctl_handler(tas5404_codec, TAS5404_15_01_VIR_CLIP_OTW_N,
                                NULL, refa04_ctl_get);
    board->ops = &am_snd_refa04.board_ops;

    ssdk_printf(SSDK_ERR, "Func %s am board init success \n",
                __FUNCTION__);

    return true;
}

static int ref_select_board(void)
{
    int board_type = get_part_id(PART_BOARD_TYPE);
    int board_id_maj = get_part_id(PART_BOARD_ID_MAJ);
    int board_id_min = get_part_id(PART_BOARD_ID_MIN);

    if (BOARD_TYPE_REF == board_type) {
        if ((1 == board_id_maj) && (4 == board_id_min)) {
            return BOARD_X9_REFA04;
        }

        if ((1 == board_id_maj) && (3 == board_id_min)) {
            return BOARD_X9_REFA03;
        }
    }

    ssdk_printf(SSDK_ERR, "%s ref can't find hwid ,use default REFA04!!!\r\n",
            __FUNCTION__);

    return BOARD_X9_REFA04;
}

bool am_board_initialize(am_board_t *board)
{
    int board_type = ref_select_board();

    if (BOARD_X9_REFA04 == board_type) {
        return am_refa04_board_init(board);
    }
    else if (BOARD_X9_REFA03 == board_type) {
        return am_refa03_board_init(board);
    }

    return false;
}
