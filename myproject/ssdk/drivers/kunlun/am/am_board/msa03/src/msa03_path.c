static bool msa03_set_path_vol(am_path_t *path, ak7738_dsp_type_t dsp_id,
                               unsigned int component_id, unsigned int vol)
{
    am_codec_t *ak7738_codec =
        am_board_find_codec(path->board, MSA03_CODEC_AK7738);
    unsigned char vol_index =
        am_get_linear_vol(vol, MSA03_VOLUME_MAX, MSA03_VOLUME_MIN);
    unsigned char params_vol[3];
    unsigned int param_len;
    bool ret;

    if (!ak7738_codec) {
        ssdk_printf(SSDK_ERR, "Func %s ak7738_codec is NULL \n", __FUNCTION__);
        ERRCODE_PRINT(MOD_ID_SYS_SERVICE_AUDIO, AUDIO_MANAGER_SVC,
                      RET_ERR_SETVOL_FAILED, vol);
        return false;
    }

    params_vol[0] = dsp_id;
    params_vol[1] = component_id;
    params_vol[2] = vol_index;
    param_len = 3;

    ret =
        am_set_cofficient(ak7738_codec, AK7738_COFF_VOL, param_len, params_vol);
    am_delay(1);

    return ret;
}

