static bool refa04_set_path_mute(am_path_t *path, bool mute)
{
    am_codec_t *ak7738_codec =
        am_board_find_codec(path->board, REFA04_CODEC_AK7738);
    bool ret;

    if (!ak7738_codec) {
        ERRCODE_PRINT(MOD_ID_SYS_SERVICE_AUDIO, AUDIO_MANAGER_SVC,
                      RET_ERR_MUTE_FAILED, mute);
        ssdk_printf(SSDK_ERR, "Func %s ak7738_codec is NULL \n", __FUNCTION__);
        return false;
    }

    if (false == mute) {
        ret = am_write_ctl(ak7738_codec, AK7738_67_40_AD1MUTE, 0x0);
        _CHECK_RET(ret);
        ret = am_write_ctl(ak7738_codec, AK7738_67_20_AD2MUTE, 0x0);
        _CHECK_RET(ret);
    }
    else {
        ret = am_write_ctl(ak7738_codec, AK7738_67_40_AD1MUTE, 0x1);
        _CHECK_RET(ret);
        ret = am_write_ctl(ak7738_codec, AK7738_67_20_AD2MUTE, 0x1);
        _CHECK_RET(ret);
    }

    return true;
}

