/*=================================================================================================
** EEPROM地址分配 V2 (M24512, 每页128字节, 共64KB/512页)
** 重排原则: 按类型分区 + 每区预留余量(小区≥1页富余/协议区1-2KB)
**
** 地址      内容                     当前字节   预留至    说明
** ------------------------------------------------------------------------------
** 0x0000    系统配置标志(u32)         4         0x0080
** 0x0080    设备序列号               24         0x0100
** 0x0100    预留(原V1小参数位)                0x0200
** 0x0200    电流零飘校准(u16)          8        0x0280
** 0x0280    时钟统计(u16)             26        0x0300    时钟/故障时间/运行时间/工作模式
** 0x0300    SOH充放电统计(u16)         44        0x0380    SOH/状态/次数/故障数
** 0x0380    组1容量能量校正(u32)       76        0x0400
** 0x0400    组2容量能量校正(u32)       76        0x0480
** 0x0480    SOC容量结构(u32)           40        0x0500
** 0x0500    SOE能量结构(u32)           40        0x0580
** 0x0580    历史充放电(u32)            48        0x0600
** 0x0600    DOD/SOS统计(u16)           56        0x0680    含DOD次数
** 0x0680    预留小参数扩展                     0x0FFF
** ---------- 协议参数块(100-104连续分配) ----------
** 0x1000    100系统通用参数(u16)      18        0x1400    1KB
** 0x1400    101系统高级参数(u16)      32        0x1800    1KB,可扩至64字
** 0x1800    102协议参数(u16)          172       0x2000    2KB,约6倍余量
** 0x2000    103协议参数(u16)          144       0x2800    2KB
** 0x2800    104协议参数(u8)            62       0x3000    2KB
** 0x3000    预留(协议块扩展/新协议)             0x3FFF
** 0x4000    组1历史DOD记录V3(u16)    1004       0x4400    页对齐
** 0x4400    组2历史DOD记录V3(u16)    1004       0x4800    页对齐
** 0x4800    预留新协议(116/下级设备查询等)      0x7FFF
**===============================================================================================*/

