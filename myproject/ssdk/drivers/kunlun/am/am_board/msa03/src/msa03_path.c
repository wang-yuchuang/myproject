static bool am_msa03_board_init(am_board_t *board)
{
    am_codec_t *ak7738_codec;

    /* register all path for board */
    am_board_add_path(board, &idle_path);
    am_board_add_path(board, &hifi_playback_path);
    am_board_add_path(board, &hifi_capture_path);
    am_board_add_path(board, &cluster_playback_path);
    am_board_add_path(board, &safety_playback_path);
    am_board_add_path(board, &fm_playback_path);
    am_board_add_path(board, &nav_playback_path);
    am_board_add_path(board, &phone_playback_path);
    am_board_add_path(board, &phone_playback_path);
    am_board_add_path(board, &phone_capture_path);

    /* register all codec for board */
    ak7738_codec = ak7738_codec_create(MSA03_CODEC_AK7738);
    am_board_add_codec(board, ak7738_codec);
    board->ops = &msa03_board_ops;

    ak7738_drvdata.handle = i2c_get_adap_dev(AUDIO_I2C_INSTANCE);

    if (!ak7738_drvdata.handle) {
        ssdk_printf(SSDK_ERR, "Err Func %s create i2c handle faild\n",
                __FUNCTION__);
        ERRCODE_PRINT(MOD_ID_SYS_SERVICE_AUDIO, AUDIO_MANAGER_SVC,
                      RET_ERR_INIT_FAILED, AUDIO_I2C_INSTANCE);
        return false;
    }

    am_codec_set_virctl_handler(ak7738_codec, AK7738_106_01_VIR_HWPDN,
                                msa03_ak7738_ctl_pdn_put, NULL);
    am_codec_set_drvdata(ak7738_codec, &ak7738_drvdata);
    board->ops = &msa03_board_ops;

    return true;
}

bool am_board_initialize(am_board_t *board)
{
    return am_msa03_board_init(board);
}
