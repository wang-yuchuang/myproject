static bool msa03_ak7738_ctl_pdn_put(am_codec_t *codec, unsigned int ctl,
                                     unsigned int enable)
{
    bool ioret = true;

    printf("\t%s enable =%d,\n", __FUNCTION__, enable);

    gpio_config(&g_gpio_dev, AUDIO_DSP_RST_N, GPIO_OUT);

    if (enable) {
        gpio_set(&g_gpio_dev, AUDIO_DSP_RST_N, 1);
    }
    else {
        gpio_set(&g_gpio_dev, AUDIO_DSP_RST_N, 0);
    }

    return ioret;
}

