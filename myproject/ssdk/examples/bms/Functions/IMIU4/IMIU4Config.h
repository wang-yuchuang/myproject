#ifndef __IMIU4CONFIG_H_
#define __IMIU4CONFIG_H_

#include "BSPTypeDef.h"
#include "DEVCAN.h"

/*=================================================================================================
** IMIU4设备地址配置
** 本工程支持最多2台IMIU4作为下级设备
**===============================================================================================*/
/*1#IMIU4设备通信地址*/
#define IMIU4_1_DEV_ADDR        (20)
/*2#IMIU4设备通信地址*/
#define IMIU4_2_DEV_ADDR        (21)

/*=================================================================================================
** IMIU4通信通道配置
**===============================================================================================*/
/*IMIU4通信CAN通道: 使用CAN2*/
#define IMIU4_CAN_CH            (eCAN2)

/*=================================================================================================
** IMIU4通信超时和重试配置
**===============================================================================================*/
/*周期上报间隔(ms): IMIU4主动更新数据周期*/
#define IMIU4_REPORT_PERIOD_MS  (1000)
/*响应超时时间(ms): 等待IMIU4回复超时*/
#define IMIU4_RESP_TIMEOUT_MS   (500)
/*最大重试次数: 命令发送失败重试*/
#define IMIU4_MAX_RETRY         (3)

/*=================================================================================================
** IMIU4采样信息长度定义
** 主索引51: 采样信息(20个s16元素)
**===============================================================================================*/
/*采样信息数组长度*/
#define IMIU4_SAMPINFO_LEN      (20)

/*=================================================================================================
** IMIU4故障告警信息长度定义
** 主索引57: 故障告警信息(6个u16元素)
**===============================================================================================*/
/*告警信息数组长度*/
#define IMIU4_ALMINFO_LEN       (6)

/*=================================================================================================
** IMIU4设备信息长度定义
** 主索引2: 设备信息
**===============================================================================================*/
/*设备信息数组长度*/
#define IMIU4_DEVINFO_LEN       (8)

/*=================================================================================================
** IMIU4绝缘检测控制命令值定义
**===============================================================================================*/
/*绝缘检测命令: 自动检测*/
#define IMIU4_INSU_AUTO         (0)
/*绝缘检测命令: 开始检测*/
#define IMIU4_INSU_START        (1)
/*绝缘检测命令: 停止检测*/
#define IMIU4_INSU_STOP         (2)

/*=================================================================================================
** IMIU4继电器控制定义
**===============================================================================================*/
/*继电器选择: 所有继电器*/
#define IMIU4_READY_ALL         (0)
/*继电器选择: DO1继电器*/
#define IMIU4_READY_DO1         (1)
/*继电器选择: DO2继电器*/
#define IMIU4_READY_DO2         (2)

/*继电器状态: 断开*/
#define IMIU4_READY_OFF         (0)
/*继电器状态: 闭合*/
#define IMIU4_READY_ON          (1)

#endif