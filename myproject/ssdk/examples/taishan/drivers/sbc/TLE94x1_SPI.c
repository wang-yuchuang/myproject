struct spi_controller sbc_spi_controller;
struct spi_device sbc_spi_device = {0};
struct spi_config sbc_spi_config = {
    .idle = 0x1f,
    .timeout = 0x1f,
    .tim_ctrl = FV_SPI_TIM_CTRL_START_DLY(0) | FV_SPI_TIM_CTRL_END_DLY(0) |
                FV_SPI_TIM_CTRL_FRM_DLY(0),
    .bus_flags = SPI_TX_IRQ_ENABLE | SPI_RX_IRQ_ENABLE,
    .slave_nss_pol = 0,
    .dev_flags = 0,
    .dmac = 0,
};

struct spi_controller_config sbc_spi_controller_conf = {
    .id = 0,
    .base = APB_SPI7_BASE,
    .irq = SPI7_SPI_INTR_NUM,
    .mode = SPI_MODE_1,
    .slave = false,
    .clk = CLK_NODE(g_ckgen_ip_spi_sf_5_to_8),
    .polling_mode = false,
    .bits_per_word_in_slave = 8,
};

struct spi_device_config sbc_spi_device_conf = {
    .mode = SPI_MODE_1,
    .freq_hz = 1000000,
    .bits_per_word = 8,
    .chip_select = 0,
    .is_lsb = 1,
    .byte_swap = 0,
    .start_delay = 0,
    .end_delay = 0,
};

gpio_dev_t *gpio_dev = NULL;
pinctrl_t *pinctrl = NULL;

extern gpio_dev_t g_gpio_safety;
extern gpio_dev_t g_gpio_ap;
#define GPIO_INSTANCE(pin)                                                     \
    (((pin) < TAISHAN_SAFETY_PIN_NUM) ? &g_gpio_safety : &g_gpio_ap)

extern pinctrl_t g_pinctrl_safety;
extern pinctrl_t g_pinctrl_ap;
#define PINCTRL_INSTANCE(pin)                                                  \
    (((pin) < TAISHAN_SAFETY_PIN_NUM) ? &g_pinctrl_safety : &g_pinctrl_ap)

#define SBC_SPI_CS 111
#define SBC_SPI_SET gpio_set(gpio_dev, SBC_SPI_CS, 1);
#define SBC_SPI_RESET gpio_set(gpio_dev, SBC_SPI_CS, 0);

