static const struct ov5640_mode_info *
ov5640_find_mode(struct ov5640_dev *sensor, enum ov5640_frame_rate fr,
                 uint32_t width, uint32_t height, bool nearest)
{
    const struct ov5640_mode_info *mode;
    sensor_debug("%s\n", __func__);
    mode = vdev_find_nearest_size(ov5640_mode_data[fr],
                                  ARRAY_SIZE(ov5640_mode_data[fr]), hact, vact,
                                  width, height);

    if (!mode || (!nearest && (mode->hact != width || mode->vact != height)))
        return NULL;

    return mode;
}

/*
 * sensor changes between scaling and subsampling, go through
 * exposure calculation
 */
static int ov5640_set_mode_exposure_calc(struct ov5640_dev *sensor,
                                         const struct ov5640_mode_info *mode)
{
    uint32_t prev_shutter, prev_gain16;
    uint32_t cap_shutter, cap_gain16;
    uint32_t cap_sysclk, cap_hts, cap_vts;
    uint32_t light_freq, cap_bandfilt, cap_maxband;
    uint32_t cap_gain16_shutter;
    uint8_t average;
    int ret;

    if (!mode->reg_data)
        return -EINVAL;
    sensor_debug("%s\n", __func__);
    /* read preview shutter */
    ret = ov5640_get_exposure(sensor);

    if (ret < 0)
        return ret;

    prev_shutter = ret;
    ret = ov5640_get_binning(sensor);

    if (ret < 0)
        return ret;

    if (ret && mode->id != OV5640_MODE_720P_1280_720 &&
        mode->id != OV5640_MODE_1080P_1920_1080)
        prev_shutter *= 2;

    /* read preview gain */
    ret = ov5640_get_gain(sensor);

    if (ret < 0)
        return ret;

    prev_gain16 = ret;

    /* get average */
    ret = ov5640_read_reg(sensor, OV5640_REG_AVG_READOUT, &average);

    if (ret)
        return ret;

    /* turn off night mode for capture */
    ret = ov5640_set_night_mode(sensor);

    if (ret < 0)
        return ret;

    /* Write capture setting */
    ret = ov5640_load_regs(sensor, mode);

    if (ret < 0)
        return ret;

    /* read capture VTS */
    ret = ov5640_get_vts(sensor);

    if (ret < 0)
        return ret;

    cap_vts = ret;
    ret = ov5640_get_hts(sensor);

    if (ret < 0)
        return ret;

    if (ret == 0)
        return -EINVAL;

    cap_hts = ret;

    ret = ov5640_get_sysclk(sensor);

    if (ret < 0)
        return ret;

    if (ret == 0)
        return -EINVAL;

    cap_sysclk = ret;

    /* calculate capture banding filter */
    ret = ov5640_get_light_freq(sensor);

    if (ret < 0)
        return ret;

    light_freq = ret;

    if (light_freq == 60) {
        /* 60Hz */
        cap_bandfilt = cap_sysclk * 100 / cap_hts * 100 / 120;
    } else {
        /* 50Hz */
        cap_bandfilt = cap_sysclk * 100 / cap_hts;
    }

    if (!sensor->prev_sysclk) {
        ret = ov5640_get_sysclk(sensor);

        if (ret < 0)
            return ret;

        if (ret == 0)
            return -EINVAL;

        sensor->prev_sysclk = ret;
    }

    if (!cap_bandfilt)
        return -EINVAL;

    cap_maxband = (int)((cap_vts - 4) / cap_bandfilt);

    /* calculate capture shutter/gain16 */
    if (average > sensor->ae_low && average < sensor->ae_high) {
        /* in stable range */
        cap_gain16_shutter = prev_gain16 * prev_shutter * cap_sysclk /
                             sensor->prev_sysclk * sensor->prev_hts / cap_hts *
                             sensor->ae_target / average;
    } else {
        cap_gain16_shutter = prev_gain16 * prev_shutter * cap_sysclk /
                             sensor->prev_sysclk * sensor->prev_hts / cap_hts;
    }

    /* gain to shutter */
    if (cap_gain16_shutter < (cap_bandfilt * 16)) {
        /* shutter < 1/100 */
        cap_shutter = cap_gain16_shutter / 16;

        if (cap_shutter < 1)
            cap_shutter = 1;

        cap_gain16 = cap_gain16_shutter / cap_shutter;

        if (cap_gain16 < 16)
            cap_gain16 = 16;
    } else {
        if (cap_gain16_shutter > (cap_bandfilt * cap_maxband * 16)) {
            /* exposure reach max */
            cap_shutter = cap_bandfilt * cap_maxband;

            if (!cap_shutter)
                return -EINVAL;

            cap_gain16 = cap_gain16_shutter / cap_shutter;
        } else {
            /* 1/100 < (cap_shutter = n/100) =< max */
            cap_shutter =
                ((int)(cap_gain16_shutter / 16 / cap_bandfilt)) * cap_bandfilt;

            if (!cap_shutter)
                return -EINVAL;

            cap_gain16 = cap_gain16_shutter / cap_shutter;
        }
    }

    /* set capture gain */
    ret = ov5640_set_gain(sensor, cap_gain16);

    if (ret)
        return ret;

    /* write capture shutter */
    if (cap_shutter > (cap_vts - 4)) {
        cap_vts = cap_shutter + 4;
        ret = ov5640_set_vts(sensor, cap_vts);

        if (ret < 0)
            return ret;
    }

    /* set exposure */
    return ov5640_set_exposure(sensor, cap_shutter);
}

