static int ov5640_get_light_freq(struct ov5640_dev *sensor)
{
    /* get banding filter value */
    int ret, light_freq = 0;
    uint8_t temp, temp1;
    sensor_debug("%s\n", __func__);
    ret = ov5640_read_reg(sensor, OV5640_REG_HZ5060_CTRL01, &temp);

    if (ret)
        return ret;

    if (temp & 0x80) {
        /* manual */
        ret = ov5640_read_reg(sensor, OV5640_REG_HZ5060_CTRL00, &temp1);

        if (ret)
            return ret;

        if (temp1 & 0x04) {
            /* 50Hz */
            light_freq = 50;
        } else {
            /* 60Hz */
            light_freq = 60;
        }
    } else {
        /* auto */
        ret = ov5640_read_reg(sensor, OV5640_REG_SIGMADELTA_CTRL0C, &temp1);

        if (ret)
            return ret;

        if (temp1 & 0x01) {
            /* 50Hz */
            light_freq = 50;
        } else {
            /* 60Hz */
        }
    }

    return light_freq;
}

static int ov5640_set_bandingfilter(struct ov5640_dev *sensor)
{
    uint32_t band_step60, max_band60, band_step50, max_band50, prev_vts;
    int ret;
    sensor_debug("%s\n", __func__);
    /* read preview PCLK */
    ret = ov5640_get_sysclk(sensor);

    if (ret < 0)
        return ret;

    if (ret == 0)
        return -EINVAL;

    sensor->prev_sysclk = ret;
    printf("pclk = %d\n", ret);

    /* read preview HTS */
    ret = ov5640_get_hts(sensor);

    if (ret < 0)
        return ret;

    if (ret == 0)
        return -EINVAL;

    sensor->prev_hts = ret;

    /* read preview VTS */
    ret = ov5640_get_vts(sensor);

    if (ret < 0)
        return ret;

    prev_vts = ret;

    /* calculate banding filter */
    /* 60Hz */
    band_step60 = sensor->prev_sysclk * 100 / sensor->prev_hts * 100 / 120;
    ret = ov5640_write_reg16(sensor, OV5640_REG_AEC_B60_STEP, band_step60);

    if (ret)
        return ret;

    if (!band_step60)
        return -EINVAL;

    max_band60 = (int)((prev_vts - 4) / band_step60);
    ret = ov5640_write_reg(sensor, OV5640_REG_AEC_CTRL0D, max_band60);

    if (ret)
        return ret;

    /* 50Hz */
    band_step50 = sensor->prev_sysclk * 100 / sensor->prev_hts;
    ret = ov5640_write_reg16(sensor, OV5640_REG_AEC_B50_STEP, band_step50);

    if (ret)
        return ret;

    if (!band_step50)
        return -EINVAL;

    max_band50 = (int)((prev_vts - 4) / band_step50);
    return ov5640_write_reg(sensor, OV5640_REG_AEC_CTRL0E, max_band50);
}

static int ov5640_set_ae_target(struct ov5640_dev *sensor, int target)
{
    /* stable in high */
    uint32_t fast_high, fast_low;
    int ret;
    sensor_debug("%s\n", __func__);
    sensor->ae_low = target * 23 / 25;  /* 0.92 */
    sensor->ae_high = target * 27 / 25; /* 1.08 */

    fast_high = sensor->ae_high << 1;

    if (fast_high > 255)
        fast_high = 255;

    fast_low = sensor->ae_low >> 1;

    ret = ov5640_write_reg(sensor, OV5640_REG_AEC_CTRL0F, sensor->ae_high);

    if (ret)
        return ret;

    ret = ov5640_write_reg(sensor, OV5640_REG_AEC_CTRL10, sensor->ae_low);

    if (ret)
        return ret;

    ret = ov5640_write_reg(sensor, OV5640_REG_AEC_CTRL1B, sensor->ae_high);

    if (ret)
        return ret;

    ret = ov5640_write_reg(sensor, OV5640_REG_AEC_CTRL1E, sensor->ae_low);

    if (ret)
        return ret;

    ret = ov5640_write_reg(sensor, OV5640_REG_AEC_CTRL11, fast_high);

    if (ret)
        return ret;

    return ov5640_write_reg(sensor, OV5640_REG_AEC_CTRL1F, fast_low);
}

