typedef struct tagQuickParamItem
{
    int                 nCombined_ParamId; //will be generated by paramId*1000 + sub_paramId;
    WEB_PARAM_VALUE*    pOrigParam;
    int                 nDevId; //just for setting purpose
    BOOL                bIsBlobparam; //false-normal, true-blob
    //only for sub-blob param, usually 
    WEB_SUBBLOB_ITEM*   pSubBlobParam;
}QUICK_PARAM_VALUE;

