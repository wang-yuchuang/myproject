#ifndef _BITS_MASK_
#define _BITS_MASK_(h_bit, l_bit)                                              \
    (((~0UL) - (1UL << (l_bit)) + 1) & (~0UL >> (32 - 1 - (h_bit))))
#endif

#ifndef VALUE_MASK
#define VALUE_MASK(val, shift) ((val) << (shift))
#endif

#ifndef _BIT_
#define _BIT_(n) (1 << (n))
#endif

#define SPDIF_SAMPLE_RATE_CALC(SPDIF_CLK, SAMPLE_RATE)                         \
    ((2 * (SPDIF_CLK) + 128 * (SAMPLE_RATE)) / (2 * 128 * (SAMPLE_RATE)) - 1)

